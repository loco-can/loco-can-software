#!/usr/bin/env node
/**
 * Pack the programmer webservice into LittleFS data/.
 *
 * The Next.js UI lives in a sibling repo (programmer). This script runs
 * `npm run firmware` there and copies the gzipped export into:
 *   - src/module/programmer/data   (PlatformIO data_dir)
 *   - data                         (Arduino IDE, next to the .ino)
 */

import { spawnSync } from "node:child_process";
import {
  cp,
  mkdir,
  readdir,
  readFile,
  rm,
  stat,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pioData = path.join(root, "src/module/programmer/data");
const arduinoData = path.join(root, "data");

async function isDir(file) {
  try {
    return (await stat(file)).isDirectory();
  } catch {
    return false;
  }
}

async function hasFirmwareScript(dir) {
  try {
    const pkg = JSON.parse(await readFile(path.join(dir, "package.json"), "utf8"));
    return Boolean(pkg?.scripts?.firmware);
  } catch {
    return false;
  }
}

async function findUiRepo() {
  const named = process.env.LOCO_CAN_PROGRAMMER_UI;
  const candidates = [
    named,
    path.resolve(root, "../programmer"),
    path.resolve(root, "../loco-can-programmer"),
  ].filter(Boolean);

  for (const dir of candidates) {
    if ((await isDir(dir)) && (await hasFirmwareScript(dir))) {
      return dir;
    }
  }
  return null;
}

function nodeMajor() {
  return Number.parseInt(process.versions.node.split(".")[0], 10);
}

function resolveNode20() {
  if (nodeMajor() >= 20) {
    return process.execPath;
  }

  console.log(
    `System Node is ${process.version}; the programmer UI needs 20+. Bootstrapping Node 20.`
  );
  const result = spawnSync(
    "npx",
    ["-y", "node@20", "-e", "console.log(process.execPath)"],
    { encoding: "utf8", env: process.env }
  );
  if (result.error) {
    throw result.error;
  }
  if (result.status !== 0) {
    console.error(result.stderr || result.stdout);
    throw new Error("Could not download Node 20 via npx. Install Node.js 20+ and retry.");
  }
  const execPath = result.stdout.trim().split("\n").at(-1)?.trim();
  if (!execPath) {
    throw new Error("npx node@20 did not print an executable path.");
  }
  return execPath;
}

function run(cmd, args, cwd, extraEnv = {}) {
  const result = spawnSync(cmd, args, {
    cwd,
    stdio: "inherit",
    env: { ...process.env, ...extraEnv },
    shell: false,
  });
  if (result.error) {
    throw result.error;
  }
  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }
}

async function copyPacked(src, dest) {
  await mkdir(dest, { recursive: true });
  const entries = await readdir(dest);
  for (const name of entries) {
    if (name === "README.md") {
      continue;
    }
    await rm(path.join(dest, name), { recursive: true, force: true });
  }
  await cp(src, dest, { recursive: true });
}

async function main() {
  const ui = await findUiRepo();
  if (!ui) {
    console.error(
      [
        "The programmer web UI is not in this repository.",
        "",
        "Clone it next to loco-can-software as ../programmer",
        "(or set LOCO_CAN_PROGRAMMER_UI to that checkout), then rerun:",
        "",
        "  npm run firmware",
        "",
        "That repo is the Next.js app with the `firmware` script.",
      ].join("\n")
    );
    process.exit(1);
  }

  console.log(`Using programmer UI at ${ui}`);

  const nodeBin = resolveNode20();
  const npmEnv = { PATH: `${path.dirname(nodeBin)}${path.delimiter}${process.env.PATH}` };
  const modules = path.join(ui, "node_modules");
  // Native addons (Tailwind oxide) must be installed with Node 20.
  if (!(await isDir(modules)) || nodeMajor() < 20) {
    run("npm", ["install"], ui, npmEnv);
  }
  run("npm", ["run", "firmware"], ui, npmEnv);

  const packed = path.join(ui, "firmware/module/programmer/data");
  if (!(await isDir(packed))) {
    throw new Error(`Missing packed LittleFS output: ${packed}`);
  }

  await copyPacked(packed, pioData);
  await copyPacked(packed, arduinoData);
  await writeFile(
    path.join(pioData, "README.md"),
    [
      "# LittleFS data",
      "",
      "Generated by `npm run firmware` in loco-can-software.",
      "That command builds the sibling Next.js UI and gzip-copies it here.",
      "",
      "PlatformIO uploads this folder (`pio run -e programmer_v3 -t uploadfs`).",
      "Arduino IDE uses `data/` next to `loco-can-software.ino` (also filled).",
      "",
      "The access point serves these files at http://192.168.4.1/.",
      "",
    ].join("\n")
  );

  console.log(`\nCopied LittleFS image → ${path.relative(root, pioData)}`);
  console.log(`Copied LittleFS image → ${path.relative(root, arduinoData)}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
